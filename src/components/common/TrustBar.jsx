import { getDealsCount } from "@/lib/graphql/queries/deals";
import { getStoresCount } from "@/lib/graphql/queries/taxonomies";
import { stats } from "@/lib/siteConfig";

export default async function TrustBar() {
  const [dealsCount, storesCount] = await Promise.all([
    getDealsCount(),
    getStoresCount(),
  ]);

  const items = [
    { icon: <DotIcon />, value: dealsCount, label: "Total deals" },
    { icon: <StoreIcon />, value: `${storesCount}+`, label: "stores" },
    { icon: <CheckIcon />, value: stats.verified, label: "verified links" },
    { icon: <ChatIcon />, value: stats.community, label: "community" },
  ];

  const Item = ({ it }) => (
    <div className="flex items-center gap-3 shrink-0">
      <div className="flex items-center gap-2">
        {it.icon}
        <span className="text-[13px] font-bold uppercase text-text">
          {it.value}
        </span>
      </div>
      <span className="text-[13px] font-medium text-muted whitespace-nowrap">
        {it.label}
      </span>
    </div>
  );

  return (
    <section className="container-wrap pt-4">
      <div className="bg-white border border-line rounded-[12px] p-2.5 overflow-hidden">
        {/* Desktop: static centered */}
        <div className="hidden md:flex justify-center gap-10">
          {items.map((it, i) => (
            <Item key={i} it={it} />
          ))}
        </div>

        {/* Mobile: auto-scrolling marquee */}
        <div className="md:hidden overflow-hidden">
          <div className="marquee-track flex gap-8 w-max">
            {[...items, ...items].map((it, i) => (
              <Item key={i} it={it} />
            ))}
          </div>
        </div>
      </div>
    </section>
  );
}

